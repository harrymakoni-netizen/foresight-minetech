import { expect, test } from "@playwright/test";
// Spec §8 / §13.2: plan view, 3D toggle, editor with validation and undo.
test("mine plan, 3D, table and editor with live preflight", async ({ page }) => {
  await page.goto("/#mine");
  await expect(page.getByRole("heading", { name: "Mine", exact: true })).toBeVisible();
  const plan = page.getByRole("img", { name: /Plan of Mavambo training mine/ });
  await expect(plan).toBeVisible();
  await expect(plan).toContainText("Main shaft");
  await expect(plan).toContainText("East incline");
  await expect(plan).toContainText("0 declared underground");
  await page.getByRole("tab", { name: "Table" }).click();
  await expect(page.locator("table").first()).toContainText("East development");
  await expect(page.locator("table").first()).toContainText("Assumed: Fictional training-mine value; not measured");
  await page.getByRole("tab", { name: "3D" }).click();
  await expect(page.getByRole("img", { name: /3D schematic of 13 tunnels/ }).or(page.getByText(/3D view unavailable/))).toBeVisible();
  await page.getByRole("tab", { name: "Edit" }).click();
  await page.getByRole("button", { name: /New draft from revision 1/ }).click();
  const editable = page.getByRole("img", { name: /Editable plan, draft revision 2/ });
  await expect(editable).toBeVisible();
  await expect(page.getByRole("heading", { name: /Validation: 0 blocking/ })).toBeVisible();
  await page.getByRole("button", { name: "Add junction" }).click();
  await editable.scrollIntoViewIfNeeded();
  const box = (await editable.boundingBox())!;
  await page.mouse.click(box.x + box.width * 0.9, box.y + box.height * 0.85);
  await expect(page.getByRole("heading", { name: /Junction N\d+/ })).toBeVisible();
  await page.getByRole("button", { name: "Connect tunnel" }).click();
  await page.getByRole("button", { name: /^Junction N\d+/ }).click();
  await page.getByRole("button", { name: /^Junction J5/ }).click();
  await expect(page.getByRole("heading", { name: /Tunnel T14/ })).toBeVisible();
  await expect(page.getByText("Tunnel T14 width is not entered.")).toBeVisible();
  await expect(page.getByRole("button", { name: /Save and publish/ })).toBeDisabled();
  await page.getByLabel("Width (m)", { exact: true }).fill("2.4");
  await page.getByLabel("Width (m) source note", { exact: true }).fill("Paced at the face");
  await page.getByLabel("Width (m) source", { exact: true }).selectOption("measured");
  await expect(page.getByText("Tunnel T14 width is not entered.")).toHaveCount(0);
  await page.getByRole("button", { name: "Undo" }).click();
  await page.getByRole("button", { name: "Redo" }).click();
  await page.getByRole("button", { name: "Save draft" }).click();
  await expect(page.getByRole("status").filter({ hasText: "Draft saved" })).toBeVisible();
});

test("fan curve entry: a curve with a duty is warned about, flows that do not increase block publishing", async ({ page }) => {
  await page.goto("/#mine");
  await page.getByRole("tab", { name: "Edit" }).click();
  const fresh = page.getByRole("button", { name: /New draft from revision/ });
  if (await fresh.count()) await fresh.click();
  await expect(page.getByRole("img", { name: /Editable plan, draft revision/ })).toBeVisible();
  await page.getByRole("button", { name: /^Tunnel T13/ }).click();
  const curve = page.getByLabel(/Pressure–quantity curve/);
  await curve.fill("0, 300\n40, 0");
  await curve.blur();
  await expect(page.getByText(/has both a curve and a fixed duty/)).toBeVisible();
  await curve.fill("0, 300\n0, 100");
  await curve.blur();
  await expect(page.getByText(/curve flows must increase strictly/)).toBeVisible();
  await expect(page.getByRole("button", { name: /Save and publish/ })).toBeDisabled();
  await curve.fill("");
  await curve.blur();
  await expect(page.getByText(/curve flows must increase strictly/)).toHaveCount(0);
});
