test("a demo SOS stays open after acknowledgement and leaves the roll intact", async ({ page }) => {
  test.skip(process.env.FORESIGHT_PERSONNEL_DEMO !== "1", "Enable the isolated personnel demo.");
  await page.goto("/");
  await page.getByRole("button", { name: "Manual check-in" }).click();
  const registration = page.getByRole("dialog");
  await registration.getByLabel("Person").selectOption({ label: "Rudo C. (fictional)" });
  await registration.getByLabel("Consent note (how it was given)").fill("Consent recorded at the bench station");
  await registration.getByRole("button", { name: "Record consent given in person" }).click();
  await registration.getByLabel("Shaft").selectOption({ label: "2. East incline" });
  await registration.getByRole("button", { name: "Register check-in" }).click();
  await expect(page.getByRole("article", { name: /East incline: 1 declared underground/ })).toBeVisible();
  const monitor = page.getByRole("region", { name: "Personnel observations" });
  await monitor.getByLabel("Observation source").selectOption("demo");
  await monitor.getByText("Sensor network (0 receivers)").click();
  await monitor.getByLabel("Device ID").fill("east-bench");
  await monitor.getByLabel("Receiver zone").selectOption("zone-b");
  await monitor.getByRole("button", { name: "Register device" }).click();
  await expect(monitor.getByText("Device registered.", { exact: true })).toBeVisible();
  await monitor.getByLabel("Device type").selectOption("wearable");
  await monitor.getByLabel("Device ID").fill("demo-tag");
  await monitor.getByLabel("Assigned person").selectOption({ label: "Rudo C. (fictional)" });
  await monitor.getByRole("button", { name: "Register device" }).click();
  await expect(monitor.getByText("Device registered.", { exact: true })).toBeVisible();
  await monitor.getByText("Send a controlled demo event").click();
  await monitor.getByLabel("Demo receiver").selectOption("east-bench");
  await monitor.getByLabel("Demo tag").selectOption("demo-tag");
  await monitor.getByLabel("Demo event").selectOption("sos");
  await monitor.getByRole("button", { name: "Record demo event" }).click();
  await expect(monitor.getByText("SOS · Rudo C. (fictional)", { exact: true })).toBeVisible();
  await monitor.getByRole("button", { name: "Acknowledge SOS" }).click();
  await expect(monitor.getByText(/Acknowledged, still open/)).toBeVisible();
  await expect(page.getByRole("article", { name: /East incline: 1 declared underground/ })).toBeVisible();
  await monitor.getByLabel("Observation source").selectOption("physical");
  await expect(monitor.getByText("SOS · Rudo C. (fictional)", { exact: true })).toHaveCount(0);
});
